"""Converts the time echoes' trainer card (a 240x160 indexed PNG, 16 colours, colour 0 transparent) into
include/new/trainer_card_echo_gfx.h: its tiles (tile 0 blank, the others without duplicates or flipped copies),
a 30x20 tilemap on palette ECHO_CARD_PAL_SLOT and the palette. Used by player_characters.c.
Run from the CFRU folder:  python scripts/echo_trainer_card/make_echo_trainer_card.py"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PNG = os.path.join(HERE, 'trainer_card_time_echo.png')
OUT = os.path.join(HERE, '..', '..', 'include', 'new', 'trainer_card_echo_gfx.h')
PAL_SLOT = 6 #BG palette for the card's front: the card itself loads slots 0-4
BRIGHTNESS = 0.8 #The PNG's colours are scaled by this in game: 0.8 = 20% darker

im = Image.open(PNG)
assert im.mode == 'P' and im.size == (240, 160), 'needs a 240x160 indexed PNG'
W, H = im.size
px = list(im.getdata())
assert max(px) < 16, 'only 16 colours (one palette)'
pal = im.getpalette()[:48]
pal += [0] * (48 - len(pal))

def tile_at(tx, ty):
    return tuple(px[(ty * 8 + y) * W + tx * 8 + x] for y in range(8) for x in range(8))

def flips(t):
    rows = [t[i * 8:(i + 1) * 8] for i in range(8)]
    return {(0, 0): t,
            (1, 0): tuple(v for r in rows for v in r[::-1]),
            (0, 1): tuple(v for r in rows[::-1] for v in r),
            (1, 1): tuple(v for r in rows[::-1] for v in r[::-1])}

tiles = [tuple([0] * 64)] #Tile 0 is blank: the card fills empty map areas with it
index = {tiles[0]: (0, 0, 0)}
tilemap = []
for ty in range(20):
    for tx in range(30):
        t = tile_at(tx, ty)
        found = None
        for (hf, vf), v in flips(t).items():
            if v in index:
                n, h0, v0 = index[v]
                found = (n, hf ^ h0, vf ^ v0)
                break
        if found is None:
            index[t] = (len(tiles), 0, 0)
            found = (len(tiles), 0, 0)
            tiles.append(t)
        n, hf, vf = found
        tilemap.append(n | (hf << 10) | (vf << 11) | (PAL_SLOT << 12))

def tile_bytes(t):
    return bytes((t[i] & 0xF) | ((t[i + 1] & 0xF) << 4) for i in range(0, 64, 2))

pal = [round(c * BRIGHTNESS) for c in pal]
gba_pal = [((pal[3 * i] >> 3) | ((pal[3 * i + 1] >> 3) << 5) | ((pal[3 * i + 2] >> 3) << 10)) for i in range(16)]

def words(data, per_line=8):
    vals = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    return ',\n'.join('\t' + ', '.join('0x%08X' % v for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line))

def halfs(vals, per_line=15):
    return ',\n'.join('\t' + ', '.join('0x%04X' % v for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line))

tile_data = b''.join(tile_bytes(t) for t in tiles)
with open(OUT, 'w', newline='\n') as f:
    f.write('#pragma once\n\n')
    f.write('//Generated by scripts/echo_trainer_card/make_echo_trainer_card.py from trainer_card_time_echo.png: don\'t edit\n\n')
    f.write('#define ECHO_CARD_NUM_TILES %d\n' % len(tiles))
    f.write('#define ECHO_CARD_PAL_SLOT %d\n\n' % PAL_SLOT)
    f.write('static const u32 sEchoTrainerCardTiles[] =\n{\n%s\n};\n\n' % words(tile_data))
    f.write('static const u16 sEchoTrainerCardFrontTilemap[30 * 20] =\n{\n%s\n};\n\n' % halfs(tilemap))
    f.write('static const u16 sEchoTrainerCardPal[16] =\n{\n%s\n};\n' % halfs(gba_pal, 8))
print('tiles', len(tiles), '->', os.path.normpath(OUT))
